#!/usr/bin/env python3
"""SNESRecomp Tools — convert Super Nintendo / Super Famicom ROMs to
native PC games.

Pick ROMs -> they are probed instantly from their cartridge headers ->
Run Queue converts them one at a time (snesrecomp: recomp-ui
launcher, box art, save states / rewind) and packages Linux +
Windows zips. Cartridges the framework has not implemented (DSP-2/3/4,
SPC7110, S-DD1, ExLoROM/ExHiROM, ...) are flagged "needs review" up
front instead of failing halfway through a build. Failures are
logged and skipped, never fatal to the queue.
"""
